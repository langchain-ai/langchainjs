export function _modelPrefersResponsesAPI(model: string): boolean {
  const base = (
    model.startsWith("ft:") ? (model.split(":")[1] ?? model) : model
  ).replace(/-\d{4}-\d{2}-\d{2}$/, "");
  return !LEGACY_CHAT_COMPLETIONS_FAMILIES.includes(base);
}
